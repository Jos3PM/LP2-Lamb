CREATE SEQUENCE FIA_SOLICITUD_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE FIA_SOLICITUD_MATRICULA (
 id NUMBER(19) PRIMARY KEY,
 estudiante_id NUMBER(19) NOT NULL,
 plan_id NUMBER(19) NOT NULL,
 periodo VARCHAR2(30) NOT NULL,
 curso_ids VARCHAR2(3000) NOT NULL,
 creditos NUMBER(10) NOT NULL,
 monto NUMBER(12,2) NOT NULL,
 moneda VARCHAR2(3) NOT NULL,
 estado VARCHAR2(20) NOT NULL,
 fecha TIMESTAMP NOT NULL,
 CONSTRAINT UK_FIA_SOL_EST_PER UNIQUE (estudiante_id,periodo),
 CONSTRAINT FK_FIA_SOL_EST FOREIGN KEY (estudiante_id) REFERENCES FIA_ESTUDIANTE(id),
 CONSTRAINT FK_FIA_SOL_PLAN FOREIGN KEY (plan_id) REFERENCES FIA_PLAN(id)
);
