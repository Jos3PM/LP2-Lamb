-- FIA Académico v7: ejecutar en el esquema FIA_APP después de v6.
-- No crea usuarios ni contraseñas de demostración. Reejecutable para facilitar recuperación.
DECLARE
  n NUMBER;
BEGIN
  SELECT COUNT(*) INTO n FROM user_tables WHERE table_name='FIA_PROFESOR_CUENTA';
  IF n=0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE FIA_PROFESOR_CUENTA (
      username VARCHAR2(80 CHAR) PRIMARY KEY, password_hash VARCHAR2(100 CHAR) NOT NULL,
      docente_id NUMBER(19) NOT NULL, codigo VARCHAR2(30 CHAR) NOT NULL,
      correo VARCHAR2(180 CHAR) NOT NULL, activo NUMBER(1) DEFAULT 1 NOT NULL,
      creado_por VARCHAR2(80 CHAR) NOT NULL, modificado_por VARCHAR2(80 CHAR) NOT NULL,
      creado_en TIMESTAMP NOT NULL, modificado_en TIMESTAMP NOT NULL,
      CONSTRAINT FK_FIA_PROF_DOCENTE FOREIGN KEY (docente_id) REFERENCES FIA_DOCENTE_FUENTE(id),
      CONSTRAINT UK_FIA_PROF_DOCENTE UNIQUE (docente_id),
      CONSTRAINT UK_FIA_PROF_CODIGO UNIQUE (codigo),
      CONSTRAINT UK_FIA_PROF_CORREO UNIQUE (correo),
      CONSTRAINT CK_FIA_PROF_ACTIVO CHECK (activo IN (0,1))) ]';
  END IF;

  SELECT COUNT(*) INTO n FROM user_tab_columns WHERE table_name='FIA_CARGA' AND column_name='CREADO_POR';
  IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE FIA_CARGA ADD (creado_por VARCHAR2(80 CHAR))'; END IF;
  SELECT COUNT(*) INTO n FROM user_tab_columns WHERE table_name='FIA_CARGA' AND column_name='MODIFICADO_POR';
  IF n=0 THEN EXECUTE IMMEDIATE 'ALTER TABLE FIA_CARGA ADD (modificado_por VARCHAR2(80 CHAR))'; END IF;

  SELECT COUNT(*) INTO n FROM user_sequences WHERE sequence_name='FIA_CARGA_AUDIT_SEQ';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE SEQUENCE FIA_CARGA_AUDIT_SEQ START WITH 1 INCREMENT BY 1 NOCACHE'; END IF;
  SELECT COUNT(*) INTO n FROM user_tables WHERE table_name='FIA_CARGA_AUDIT';
  IF n=0 THEN
    EXECUTE IMMEDIATE q'[CREATE TABLE FIA_CARGA_AUDIT (
      id NUMBER(19) PRIMARY KEY, carga_id NUMBER(19) NOT NULL,
      accion VARCHAR2(20 CHAR) NOT NULL, actor VARCHAR2(80 CHAR) NOT NULL, fecha TIMESTAMP NOT NULL,
      CONSTRAINT FK_FIA_AUDIT_CARGA FOREIGN KEY (carga_id) REFERENCES FIA_CARGA(id)) ]';
  END IF;
  SELECT COUNT(*) INTO n FROM user_indexes WHERE index_name='IX_FIA_AUDIT_CARGA';
  IF n=0 THEN EXECUTE IMMEDIATE 'CREATE INDEX IX_FIA_AUDIT_CARGA ON FIA_CARGA_AUDIT(carga_id,fecha)'; END IF;
END;
/
COMMIT;
