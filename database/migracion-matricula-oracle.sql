-- Ejecutar una vez como usuario FIA_APP en instalaciones existentes que ya tienen los objetos FIA de planes y carga.
-- No ejecutar si estas tablas de matrícula ya existen.
-- Matrícula y pagos. Las tarifas se cargan desde la aplicación con los valores oficiales del periodo.
CREATE SEQUENCE FIA_ESTUDIANTE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE FIA_ELECCION_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE FIA_TARIFA_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE FIA_MATRICULA_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE FIA_MAT_DET_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE FIA_PAGO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE FIA_ESTUDIANTE (
 id NUMBER(19) PRIMARY KEY, codigo VARCHAR2(30 CHAR) NOT NULL, nombre VARCHAR2(180 CHAR) NOT NULL,
 correo VARCHAR2(180 CHAR), CONSTRAINT UK_FIA_EST_CODIGO UNIQUE(codigo)
);
CREATE TABLE FIA_ELECCION_CARRERA (
 id NUMBER(19) PRIMARY KEY, estudiante_id NUMBER(19) NOT NULL, plan_id NUMBER(19) NOT NULL,
 periodo VARCHAR2(30 CHAR) NOT NULL, fecha TIMESTAMP NOT NULL,
 CONSTRAINT FK_FIA_ELEC_EST FOREIGN KEY(estudiante_id) REFERENCES FIA_ESTUDIANTE(id),
 CONSTRAINT FK_FIA_ELEC_PLAN FOREIGN KEY(plan_id) REFERENCES FIA_PLAN(id),
 CONSTRAINT UK_FIA_ELECCION UNIQUE(estudiante_id,periodo)
);
CREATE TABLE FIA_TARIFA (
 id NUMBER(19) PRIMARY KEY, periodo VARCHAR2(30 CHAR) NOT NULL, monto_base NUMBER(12,2) NOT NULL,
 por_credito NUMBER(12,2) NOT NULL, moneda VARCHAR2(3 CHAR) NOT NULL, actualizado TIMESTAMP NOT NULL,
 CONSTRAINT UK_FIA_TARIFA_PERIODO UNIQUE(periodo),
 CONSTRAINT CK_FIA_TARIFA_BASE CHECK(monto_base >= 0), CONSTRAINT CK_FIA_TARIFA_CRED CHECK(por_credito >= 0)
);
CREATE TABLE FIA_MATRICULA (
 id NUMBER(19) PRIMARY KEY, estudiante_id NUMBER(19) NOT NULL, plan_id NUMBER(19) NOT NULL,
 periodo VARCHAR2(30 CHAR) NOT NULL, estado VARCHAR2(20 CHAR) NOT NULL, creditos NUMBER(10) NOT NULL,
 monto NUMBER(12,2) NOT NULL, pagado NUMBER(12,2) NOT NULL, moneda VARCHAR2(3 CHAR) NOT NULL, fecha TIMESTAMP NOT NULL,
 CONSTRAINT FK_FIA_MAT_EST FOREIGN KEY(estudiante_id) REFERENCES FIA_ESTUDIANTE(id),
 CONSTRAINT FK_FIA_MAT_PLAN FOREIGN KEY(plan_id) REFERENCES FIA_PLAN(id),
 CONSTRAINT UK_FIA_MAT_EST_PER UNIQUE(estudiante_id,periodo),
 CONSTRAINT CK_FIA_MAT_EST CHECK(estado IN ('PENDIENTE','PARCIAL','PAGADA')),
 CONSTRAINT CK_FIA_MAT_IMPORTE CHECK(monto >= 0 AND pagado >= 0 AND pagado <= monto),
 CONSTRAINT CK_FIA_MAT_CREDITOS CHECK(creditos >= 0)
);
CREATE TABLE FIA_MATRICULA_DET (
 id NUMBER(19) PRIMARY KEY, matricula_id NUMBER(19) NOT NULL, curso_id NUMBER(19) NOT NULL,
 curso VARCHAR2(300 CHAR) NOT NULL, creditos NUMBER(10) NOT NULL,
 CONSTRAINT FK_FIA_MATDET_MAT FOREIGN KEY(matricula_id) REFERENCES FIA_MATRICULA(id),
 CONSTRAINT FK_FIA_MATDET_CUR FOREIGN KEY(curso_id) REFERENCES FIA_CURSO(id),
 CONSTRAINT UK_FIA_MAT_CURSO UNIQUE(matricula_id,curso_id), CONSTRAINT CK_FIA_MATDET_CRED CHECK(creditos >= 0)
);
CREATE TABLE FIA_PAGO (
 id NUMBER(19) PRIMARY KEY, matricula_id NUMBER(19) NOT NULL, monto NUMBER(12,2) NOT NULL,
 metodo VARCHAR2(30 CHAR) NOT NULL, referencia VARCHAR2(100 CHAR), fecha TIMESTAMP NOT NULL,
 CONSTRAINT FK_FIA_PAGO_MAT FOREIGN KEY(matricula_id) REFERENCES FIA_MATRICULA(id),
 CONSTRAINT CK_FIA_PAGO_MONTO CHECK(monto > 0)
);
CREATE INDEX IX_FIA_MAT_EST_PER ON FIA_MATRICULA(estudiante_id,periodo);
CREATE INDEX IX_FIA_PAGO_MAT ON FIA_PAGO(matricula_id);

COMMIT;

