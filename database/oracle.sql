-- Ejecutar con el usuario de aplicación en un esquema vacío de Oracle 19c o posterior.
-- No crea usuarios ni incorpora contraseñas. Revisar el esquema con BD2 antes de ejecutar.
CREATE SEQUENCE FIA_CURSO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE FIA_CARGA_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE FIA_DETALLE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE FIA_PLAN (
 id NUMBER(19) PRIMARY KEY, school VARCHAR2(150 CHAR) NOT NULL,
 version_plan VARCHAR2(20 CHAR) NOT NULL, variant VARCHAR2(30 CHAR) NOT NULL,
 source VARCHAR2(300 CHAR)
);
CREATE TABLE FIA_CURSO (
 id NUMBER(19) PRIMARY KEY, plan_id NUMBER(19) NOT NULL,
 cycle NUMBER(10) NOT NULL, name VARCHAR2(300 CHAR) NOT NULL,
 credits NUMBER(10), ht NUMBER(10), hp NUMBER(10), hnp NUMBER(10), total NUMBER(10),
 prerequisites VARCHAR2(3000 CHAR), notes VARCHAR2(1500 CHAR),
 source VARCHAR2(300 CHAR), page NUMBER(10),
 CONSTRAINT FK_CURSO_PLAN FOREIGN KEY (plan_id) REFERENCES FIA_PLAN(id),
 CONSTRAINT CK_CURSO_CICLO CHECK (cycle BETWEEN 1 AND 10),
 CONSTRAINT CK_CURSO_HORAS CHECK (ht >= 0 AND hp >= 0 AND hnp >= 0 AND total = ht + hp + hnp),
 CONSTRAINT CK_CURSO_CREDITOS CHECK (credits >= 0)
);
CREATE INDEX IX_CURSO_PLAN_CICLO ON FIA_CURSO(plan_id,cycle);
CREATE TABLE FIA_DOCENTE_FUENTE (
 id NUMBER(19) PRIMARY KEY, school VARCHAR2(150 CHAR),
 name VARCHAR2(250 CHAR), course VARCHAR2(500 CHAR)
);
CREATE TABLE FIA_PROFESOR_CUENTA (
 username VARCHAR2(80 CHAR) PRIMARY KEY, password_hash VARCHAR2(100 CHAR) NOT NULL,
 docente_id NUMBER(19) NOT NULL, codigo VARCHAR2(30 CHAR) NOT NULL,
 correo VARCHAR2(180 CHAR) NOT NULL, activo NUMBER(1) DEFAULT 1 NOT NULL,
 creado_por VARCHAR2(80 CHAR) NOT NULL, modificado_por VARCHAR2(80 CHAR) NOT NULL,
 creado_en TIMESTAMP NOT NULL, modificado_en TIMESTAMP NOT NULL,
 CONSTRAINT FK_FIA_PROF_DOCENTE FOREIGN KEY (docente_id) REFERENCES FIA_DOCENTE_FUENTE(id),
 CONSTRAINT UK_FIA_PROF_DOCENTE UNIQUE (docente_id),
 CONSTRAINT UK_FIA_PROF_CODIGO UNIQUE (codigo),
 CONSTRAINT UK_FIA_PROF_CORREO UNIQUE (correo),
 CONSTRAINT CK_FIA_PROF_ACTIVO CHECK (activo IN (0,1))
);
CREATE TABLE FIA_CARGA (
 id NUMBER(19) PRIMARY KEY, plan_id NUMBER(19) NOT NULL,
 sede VARCHAR2(50 CHAR) NOT NULL, semestre VARCHAR2(30 CHAR) NOT NULL,
 contrato VARCHAR2(80 CHAR) NOT NULL, estado VARCHAR2(20 CHAR) NOT NULL,
 fecha TIMESTAMP NOT NULL, total_horas NUMBER(10),
 creado_por VARCHAR2(80 CHAR), modificado_por VARCHAR2(80 CHAR),
 CONSTRAINT FK_CARGA_PLAN FOREIGN KEY (plan_id) REFERENCES FIA_PLAN(id),
 CONSTRAINT CK_CARGA_ESTADO CHECK (estado = 'REGISTRADA'),
 CONSTRAINT CK_CARGA_HORAS CHECK (total_horas >= 0)
);
CREATE INDEX IX_CARGA_FECHA ON FIA_CARGA(fecha);
CREATE SEQUENCE FIA_CARGA_AUDIT_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE FIA_CARGA_AUDIT (
 id NUMBER(19) PRIMARY KEY, carga_id NUMBER(19) NOT NULL,
 accion VARCHAR2(20 CHAR) NOT NULL, actor VARCHAR2(80 CHAR) NOT NULL, fecha TIMESTAMP NOT NULL,
 resumen VARCHAR2(300 CHAR),
 CONSTRAINT FK_FIA_AUDIT_CARGA FOREIGN KEY (carga_id) REFERENCES FIA_CARGA(id)
);
CREATE INDEX IX_FIA_AUDIT_CARGA ON FIA_CARGA_AUDIT(carga_id,fecha);
CREATE TABLE FIA_CARGA_DETALLE (
 id NUMBER(19) PRIMARY KEY, carga_id NUMBER(19) NOT NULL,
 curso_id NUMBER(19) NOT NULL, docente_id NUMBER(19), grupo NUMBER(10) NOT NULL,
 cupos NUMBER(10), ambiente VARCHAR2(200 CHAR), condicion VARCHAR2(60 CHAR),
 modalidad VARCHAR2(60 CHAR), curso_nombre VARCHAR2(300 CHAR), ciclo NUMBER(10), creditos NUMBER(10), ht NUMBER(10), hp NUMBER(10), hnp NUMBER(10),
 horas NUMBER(10), docente_nombre VARCHAR2(250 CHAR),
 CONSTRAINT FK_DETALLE_CARGA FOREIGN KEY (carga_id) REFERENCES FIA_CARGA(id),
 CONSTRAINT FK_DETALLE_CURSO FOREIGN KEY (curso_id) REFERENCES FIA_CURSO(id),
 CONSTRAINT FK_DETALLE_DOCENTE FOREIGN KEY (docente_id) REFERENCES FIA_DOCENTE_FUENTE(id),
 CONSTRAINT UK_CARGA_CURSO_GRUPO UNIQUE (carga_id,curso_id,grupo),
 CONSTRAINT CK_DETALLE_GRUPO CHECK (grupo >= 1),
 CONSTRAINT CK_DETALLE_CUPOS CHECK (cupos >= 0),
 CONSTRAINT CK_DETALLE_HORAS CHECK (horas >= 0)
);
CREATE TABLE FIA_HORARIO (
 detalle_id NUMBER(19) NOT NULL, dia NUMBER(10), inicio NUMBER(10), fin NUMBER(10),
 CONSTRAINT FK_HORARIO_DETALLE FOREIGN KEY (detalle_id) REFERENCES FIA_CARGA_DETALLE(id),
 CONSTRAINT CK_HORARIO_DIA CHECK (dia BETWEEN 0 AND 6),
 CONSTRAINT CK_HORARIO_RANGO CHECK (inicio >= 0 AND fin <= 1440 AND inicio < fin)
);

-- Matrícula y pagos. Las tarifas se cargan desde la aplicación con los valores oficiales del periodo.
CREATE SEQUENCE FIA_ESTUDIANTE_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE FIA_ELECCION_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE FIA_TARIFA_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE FIA_MATRICULA_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE FIA_MAT_DET_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE SEQUENCE FIA_PAGO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE FIA_ESTUDIANTE (
 id NUMBER(19) PRIMARY KEY, codigo VARCHAR2(30 CHAR) NOT NULL, nombre VARCHAR2(180 CHAR) NOT NULL,
 correo VARCHAR2(180 CHAR), CONSTRAINT UK_FIA_EST_CODIGO UNIQUE(codigo)
);
CREATE TABLE FIA_ELECCION_CARRERA (
 id NUMBER(19) PRIMARY KEY, estudiante_id NUMBER(19) NOT NULL, plan_id NUMBER(19) NOT NULL,
 periodo VARCHAR2(30 CHAR) NOT NULL, fecha TIMESTAMP NOT NULL,
 CONSTRAINT FK_FIA_ELEC_EST FOREIGN KEY(estudiante_id) REFERENCES FIA_ESTUDIANTE(id),
 CONSTRAINT FK_FIA_ELEC_PLAN FOREIGN KEY(plan_id) REFERENCES FIA_PLAN(id),
 CONSTRAINT UK_FIA_ELECCION UNIQUE(estudiante_id,periodo)
);
CREATE TABLE FIA_TARIFA (
 id NUMBER(19) PRIMARY KEY, periodo VARCHAR2(30 CHAR) NOT NULL, monto_base NUMBER(12,2) NOT NULL,
 por_credito NUMBER(12,2) NOT NULL, moneda VARCHAR2(3 CHAR) NOT NULL, actualizado TIMESTAMP NOT NULL,
 CONSTRAINT UK_FIA_TARIFA_PERIODO UNIQUE(periodo),
 CONSTRAINT CK_FIA_TARIFA_BASE CHECK(monto_base >= 0), CONSTRAINT CK_FIA_TARIFA_CRED CHECK(por_credito >= 0)
);
CREATE TABLE FIA_MATRICULA (
 id NUMBER(19) PRIMARY KEY, estudiante_id NUMBER(19) NOT NULL, plan_id NUMBER(19) NOT NULL,
 periodo VARCHAR2(30 CHAR) NOT NULL, estado VARCHAR2(20 CHAR) NOT NULL, creditos NUMBER(10) NOT NULL,
 monto NUMBER(12,2) NOT NULL, pagado NUMBER(12,2) NOT NULL, moneda VARCHAR2(3 CHAR) NOT NULL, fecha TIMESTAMP NOT NULL,
 CONSTRAINT FK_FIA_MAT_EST FOREIGN KEY(estudiante_id) REFERENCES FIA_ESTUDIANTE(id),
 CONSTRAINT FK_FIA_MAT_PLAN FOREIGN KEY(plan_id) REFERENCES FIA_PLAN(id),
 CONSTRAINT UK_FIA_MAT_EST_PER UNIQUE(estudiante_id,periodo),
 CONSTRAINT CK_FIA_MAT_EST CHECK(estado IN ('PENDIENTE','PARCIAL','PAGADA')),
 CONSTRAINT CK_FIA_MAT_IMPORTE CHECK(monto >= 0 AND pagado >= 0 AND pagado <= monto),
 CONSTRAINT CK_FIA_MAT_CREDITOS CHECK(creditos >= 0)
);
CREATE TABLE FIA_MATRICULA_DET (
 id NUMBER(19) PRIMARY KEY, matricula_id NUMBER(19) NOT NULL, curso_id NUMBER(19) NOT NULL,
 curso VARCHAR2(300 CHAR) NOT NULL, creditos NUMBER(10) NOT NULL,
 CONSTRAINT FK_FIA_MATDET_MAT FOREIGN KEY(matricula_id) REFERENCES FIA_MATRICULA(id),
 CONSTRAINT FK_FIA_MATDET_CUR FOREIGN KEY(curso_id) REFERENCES FIA_CURSO(id),
 CONSTRAINT UK_FIA_MAT_CURSO UNIQUE(matricula_id,curso_id), CONSTRAINT CK_FIA_MATDET_CRED CHECK(creditos >= 0)
);
CREATE TABLE FIA_PAGO (
 id NUMBER(19) PRIMARY KEY, matricula_id NUMBER(19) NOT NULL, monto NUMBER(12,2) NOT NULL,
 metodo VARCHAR2(30 CHAR) NOT NULL, referencia VARCHAR2(100 CHAR), fecha TIMESTAMP NOT NULL,
 CONSTRAINT FK_FIA_PAGO_MAT FOREIGN KEY(matricula_id) REFERENCES FIA_MATRICULA(id),
 CONSTRAINT CK_FIA_PAGO_MONTO CHECK(monto > 0)
);
CREATE INDEX IX_FIA_MAT_EST_PER ON FIA_MATRICULA(estudiante_id,periodo);
CREATE INDEX IX_FIA_PAGO_MAT ON FIA_PAGO(matricula_id);

CREATE TABLE FIA_AGENDA_LOCK (id NUMBER(19) PRIMARY KEY);
