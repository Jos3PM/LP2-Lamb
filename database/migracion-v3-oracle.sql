-- Ejecutar una sola vez sobre un esquema FIA_APP que ya tiene matricula y planes.
ALTER TABLE FIA_CURSO ADD (horario VARCHAR2(300), cupos NUMBER(10) DEFAULT 30 NOT NULL);
ALTER TABLE FIA_ESTUDIANTE ADD (telefono VARCHAR2(30), apoderado VARCHAR2(180));
CREATE TABLE FIA_ALUMNO_CUENTA (
 username VARCHAR2(80) PRIMARY KEY,
 password_hash VARCHAR2(100) NOT NULL,
 estudiante_id NUMBER(19) NOT NULL,
 puede_editar_carrera NUMBER(1) DEFAULT 0 NOT NULL,
 CONSTRAINT FK_FIA_CUENTA_EST FOREIGN KEY (estudiante_id) REFERENCES FIA_ESTUDIANTE(id)
);
CREATE SEQUENCE FIA_APROBADO_SEQ START WITH 1 INCREMENT BY 1 NOCACHE;
CREATE TABLE FIA_CURSO_APROBADO (
 id NUMBER(19) PRIMARY KEY,
 estudiante_id NUMBER(19) NOT NULL,
 curso_id NUMBER(19) NOT NULL,
 CONSTRAINT UK_FIA_APROBADO UNIQUE (estudiante_id, curso_id),
 CONSTRAINT FK_FIA_APR_EST FOREIGN KEY (estudiante_id) REFERENCES FIA_ESTUDIANTE(id),
 CONSTRAINT FK_FIA_APR_CUR FOREIGN KEY (curso_id) REFERENCES FIA_CURSO(id)
);
